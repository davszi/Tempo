"""Simulator: virtual players for TEMPO training data.

clients.py (archetypes, per-player spread, the client), memory/ (hidden memory
models), recall.py (per-move recall and latency), practice.py (repertoire,
new lines, scheduling), grading.py (Again/Hard/Good/Easy and the session
record), generate.py (writes a dataset).

Owner: docs/topics/synthetic-clients/record.md

Typical use (no data is generated by importing this package)::

    from tempo_ml.simulator import Line, build_population

    clients = build_population({"blitzer": 2, "balanced": 2, "diligent": 2}, seed=7)
    line = Line("Ruy Lopez: Berlin Defense", num_moves=8)
    c = clients[0]
    c.learn(line, day=0.0)            # Learning Mode, status "new"
    out = c.review(line, day=2.4)     # Repeating Mode, status "review"
    out.record                        # one review-dataset row
"""

