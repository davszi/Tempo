"""Write results/tables.md from results/scores.json (no computation beyond rounding).

    python experiments/2026-11-14-fsrs-memory/tables.py experiments/2026-11-14-fsrs-memory/results
"""

import json
import sys
from pathlib import Path

res = Path(sys.argv[1])
sc = json.loads((res / "scores.json").read_text())
ROWS = [("constant_base_rate", "Constant (fit pass rate)"), ("default", "FSRS-6 defaults"),
        ("A1", "A1: py-fsrs, pass/fail"), ("A1c", "A1c: shared trainer, pass/fail"),
        ("B1", "B1: shared trainer, true chance (diagnostic)")]
out = ["# Results tables", "", "Generated by `tables.py` from `scores.json`. pp = percentage points.", ""]
for name, S in sc["sets"].items():
    for clock in ("exact", "calendar"):
        R = S[clock]
        out += [f"## {name} clients ({S['clients']} clients, {S['reviews']:,} tested reviews), {clock} clock", "",
                "| Weights | Log-loss | Brier | RMSE(bins) pp | AUC | RMSE vs truth pp | MAE vs truth pp | Mean predicted | Observed |",
                "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
        for key, label in ROWS:
            m = R[key]
            out.append(f"| {label} | {m['log_loss']:.4f} | {m['brier']:.4f} | {100 * m['rmse_bins']:.1f} | {m['auc']:.3f} | "
                       f"{100 * m['rmse_vs_truth']:.1f} | {100 * m['mae_vs_truth']:.1f} | {100 * m['mean_predicted']:.1f}% | "
                       f"{100 * m['observed_success']:.1f}% |")
        out += ["", "Paired log-loss gain (positive = the second-named weights are better), 95% interval over 1,000 resamples of clients:", "",
                "| Comparison | Gain | 95% interval |", "|---|---:|---:|"]
        for k, (g, lo, hi) in R["paired"].items():
            out.append(f"| {k} | {g:+.4f} | {lo:+.4f} to {hi:+.4f} |")
        out += ["", "Days to a 90% pass chance, predicted minus true (median; negative = too early):", "",
                "| Weights | All sessions | < 7 d | 7–30 d | ≥ 30 d | Share too early |", "|---|---:|---:|---:|---:|---:|"]
        for key, label in ROWS[1:]:
            d = R[key]["days"]
            b = d["bands"]
            out.append(f"| {label} | {d['median_error']:+.2f} | {b['lt7']['median_error']:+.2f} | {b['7to30']['median_error']:+.1f} | "
                       f"{b['ge30']['median_error']:+.1f} | {100 * d['share_too_early']:.1f}% |")
        out.append("")
(res / "tables.md").write_text("\n".join(out))
print(f"wrote {res / 'tables.md'}")
