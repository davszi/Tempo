"""Collect the raw benchmark numbers into ``results/benchmark-data.md``.

    python experiments/2026-11-13-fsrs-synthetic-v2/benchmark_data.py

Reads only the JSON outputs in ``results/``; nothing is recomputed.
"""

import json
from pathlib import Path

RES = Path(__file__).resolve().parent / "results"
A = json.loads((RES / "binary" / "metrics.json").read_text())
B = json.loads((RES / "true-recall" / "metrics.json").read_text())
H = json.loads((RES / "holdout_benchmark.json").read_text())
V = json.loads((RES / "v1_comparison.json").read_text())
f4 = lambda x: f"{x:.4f}"
pc = lambda x: f"{100*x:.2f}%"
dd = lambda x: f"{x:+.3f}"
out = []
w = out.append


def prob_table(rows):
    w("| Model | Reviews | Log-loss | Brier | RMSE(bins) | AUC | RMSE vs truth | MAE vs truth | Mean predicted | Observed pass |")
    w("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
    for n, m in rows:
        w(f"| {n} | {m['reviews']:,} | {f4(m['log_loss'])} | {f4(m['brier'])} | {f4(m['rmse_bins'])} | {f4(m['auc'])} | {f4(m['rmse_vs_truth'])} | {f4(m['mae_vs_truth'])} | {pc(m['mean_predicted'])} | {pc(m['observed_success'])} |")
    w("")


def days_table(rows):
    w("| Model | Sessions | Median error (d) | Median abs. error (d) | Median rel. error | Too early | Mean error (d) | Median true (d) | Median predicted (d) | Beyond 180 d |")
    w("|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
    for n, m in rows:
        d = m["days"]
        w(f"| {n} | {d['sessions']:,} | {dd(d['median_error'])} | {d['median_abs_error']:.3f} | {100*d['median_rel_error']:+.1f}% | {pc(d['share_too_early'])} | {dd(d['mean_error'])} | {d['median_true_days']:.3f} | {d['median_pred_days']:.3f} | {d['n_beyond_horizon']} |")
    w("")


def band_table(rows, key, labels):
    w("| Group | Model | Sessions | Median error (d) | Median abs. error (d) | Median rel. error |")
    w("|---|---|---:|---:|---:|---:|")
    for k, lab in labels:
        for n, m in rows:
            b = m["days"][key][k]
            w(f"| {lab} | {n} | {b['sessions']:,} | {dd(b['median_error'])} | {b['median_abs_error']:.3f} | {100*b['median_rel_error']:+.1f}% |")
    w("")


def arch(rows_by_type, title):
    w(f"### {title}")
    w("")
    w("| Type | Model | Reviews | Observed pass | Log-loss | Brier | RMSE(bins) | AUC | RMSE vs truth | Mean predicted | Days median error |")
    w("|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
    for t, rows in rows_by_type:
        for n, m in rows:
            w(f"| {t} | {n} | {m['reviews']:,} | {pc(m['observed_success'])} | {f4(m['log_loss'])} | {f4(m['brier'])} | {f4(m['rmse_bins'])} | {f4(m['auc'])} | {f4(m['rmse_vs_truth'])} | {pc(m['mean_predicted'])} | {dd(m['days']['median_error'])} |")
    w("")


BANDS = [("lt7", "True time < 7 d"), ("7to30", "True time 7–30 d"), ("ge30", "True time ≥ 30 d")]
STYPE = [("after_learning", "After a Learning session"), ("after_review", "After a review")]
T = [("Constant guess", A["test"]["constant_base_rate"]), ("Defaults", V["test"]["default"]), ("v1 (old catalog)", V["test"]["v1"]), ("A2 pass/fail", V["test"]["A2"]), ("B2 true chance", V["test"]["B2"])]
HO = [("Constant guess", H["overall"]["constant_guess"]), ("Defaults", V["holdout"]["default"]), ("v1 (old catalog)", V["holdout"]["v1"]), ("A2 pass/fail", V["holdout"]["A2"]), ("B2 true chance", V["holdout"]["B2"])]
Td, Hd = T[1:], HO[1:]

w("# Benchmark raw data: fsrs-synthetic-v2")
w("")
w("Every number shown in [`walkthrough.html`](../walkthrough.html), unrounded, plus the per-type and per-band breakdowns behind it. Generated by `benchmark_data.py` from the JSON outputs of this experiment; nothing was typed by hand. Context and interpretation: [SUMMARY](../SUMMARY.md).")
w("")
w("## Sources")
w("")
w("| File | Contents |")
w("|---|---|")
w("| `binary/metrics.json` | A2 run: fit and test metrics, per type, optimizer, split, environment |")
w("| `true-recall/metrics.json` | B2 run: same layout |")
w("| `holdout_benchmark.json` | Defaults, A2, B2 and the constant guess on the 60 hold-out clients, per type |")
w("| `v1_comparison.json` | Defaults, v1, A2 and B2 scored with the same `score()` on test and hold-out clients, and all four weight sets |")
w("")
w(f"Test clients: 60 of the 300 in `ml/data/fsrs-synthetic-v2/train/` (split per type, seed 7). Hold-out clients: 60 new clients in `ml/data/fsrs-synthetic-v2/holdout/` (seed 20261112). The constant guess always predicts the fit clients' pass rate, {A['base_rate']:.6f}.")
w("")
w("## Glossary")
w("")
w("- **Log-loss, Brier**: compare the predicted pass chance with pass (1) or fail (0). Lower is better.")
w("- **RMSE(bins)**: calibration gap. Predictions are grouped in 20 bins; root mean square gap between each bin's mean prediction and its real pass rate, weighted by bin size. Multiply by 100 for percentage points (pp).")
w("- **AUC**: chance that a random failed review got a lower prediction than a random passed one. 0.5 = coin flip, 1 = perfect.")
w("- **RMSE / MAE vs truth**: gap between the prediction and the hidden true chance of a clean session (`p_clean`). Multiply by 100 for pp.")
w("- **Days**: after each session, predicted days until the pass chance drops to 90% minus the true days. Negative = review scheduled too early. Relative error = error / true days. *Beyond 180 d*: sessions whose true time lies past the simulated horizon.")
w("")
w("## 1. Pass-chance metrics")
w("")
w("### Test clients (60)")
w("")
prob_table(T)
w("### Hold-out clients (60)")
w("")
prob_table(HO)
w("## 2. Days to 90%")
w("")
w("### Test clients")
w("")
days_table(Td)
w("### Hold-out clients")
w("")
days_table(Hd)
w("### By true time, test clients")
w("")
band_table(Td, "bands", BANDS)
w("### By true time, hold-out clients")
w("")
band_table(Hd, "bands", BANDS)
w("### By session type, test clients")
w("")
band_table(Td, "session_type", STYPE)
w("## 3. By player type")
w("")
w("v1 was not scored per type.")
w("")
types = ["balanced", "blitzer", "diligent"]
arch([(t, [("Defaults", A["test_by_archetype"][t]["fsrs6_default"]), ("A2", A["test_by_archetype"][t]["fsrs6_trained"]), ("B2", B["test_by_archetype"][t]["fsrs6_trained"])]) for t in types], "Test clients")
arch([(t, [("Defaults", H["by_archetype"][t]["fsrs6_default"]), ("A2", H["by_archetype"][t]["A2_pass"]), ("B2", H["by_archetype"][t]["B2_true"])]) for t in types], "Hold-out clients")
w("## 4. Training runs")
w("")
w("| Run | Target | Loss | Iterations | Evaluations | Converged | Final loss | Seconds | Fit reviews |")
w("|---|---|---|---:|---:|---|---:|---:|---:|")
for n, R in [("A2", A), ("B2", B)]:
    o = R["optimizer"]
    w(f"| {n} | {R['target']} | {R['loss']} | {o['iterations']} | {o['evaluations']} | {o['converged']} | {o['loss']:.6f} | {R['seconds']} | {R['fit']['fsrs6_trained']['reviews']:,} |")
w("")
w(f"Optimizer messages: A2 `{A['optimizer']['message']}`; B2 `{B['optimizer']['message']}`.")
w("")
w("Log-loss on A2's 210 fit clients, computed after the run with `train.objective` and the training mask: A2 weights 0.560232, v1 weights 0.553194.")
w("")
w("### Metrics on the fit clients (in-sample)")
w("")
prob_table([("A2", A["fit"]["fsrs6_trained"]), ("B2", B["fit"]["fsrs6_trained"])])
w("Split: fit 210 / validation 30 / test 60 clients (71,751 / 8,836 / 20,503 tested reviews). Environment: " + ", ".join(f"{k} {v}" for k, v in A["environment"].items()) + ".")
w("")
w("## 5. Weights")
w("")
W = V["weights"]
w("| Weight | Defaults | v1 | A2 | B2 |")
w("|---|---:|---:|---:|---:|")
for i in range(21):
    w(f"| w{i} | {W['default'][i]:.6f} | {W['v1'][i]:.6f} | {W['A2'][i]:.6f} | {W['B2'][i]:.6f} |")
(RES / "benchmark-data.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print(len(out), "lines")
